import { describe, expect, it } from 'vitest'
import { paymentDetails } from '../src/Format'

/**
 * Реквизиты получателя в тексте платёжного поручения. У способа СБП с
 * 08.10.2026 есть банк получателя (задача 367-3): перевод по телефону
 * поступает в конкретный банк, кассир переводит по номеру в этот банк. У
 * реквизитов, сохранённых до появления поля, банка нет — строка прежняя.
 */
describe('paymentDetails — реквизиты получателя в платёжном поручении', () => {
  it('способ СБП с банком — телефон и банк получателя', () => {
    expect(paymentDetails({ method_type: 'sbp', data: { phone: '+79001234567', bank_name: 'Сбербанк' } }, 'Иванов И. И.'))
      .toBe('СБП\nТелефон получателя: +79001234567\nБанк получателя: Сбербанк')
  })

  it('способ СБП без банка — прежняя строка, банк не печатается', () => {
    expect(paymentDetails({ method_type: 'sbp', data: { phone: '+79001234567' } }, 'Иванов И. И.'))
      .toBe('СБП\nТелефон получателя: +79001234567')
  })

  it('способ СБП с банком из одних пробелов — как без банка', () => {
    expect(paymentDetails({ method_type: 'sbp', data: { phone: '+79001234567', bank_name: '   ' } }, 'Иванов И. И.'))
      .toBe('СБП\nТелефон получателя: +79001234567')
  })
})
